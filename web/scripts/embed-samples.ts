/** Embeds the sample files into src/samples.ts so the web app (even as a single HTML file) can open them. */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..', '..', 'samples');
const names = readdirSync(dir).filter((n) => !n.endsWith('.json')).sort();
const lines = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(readFileSync(join(dir, n)).toString('base64'))},`);
writeFileSync(
  join(import.meta.dirname, '..', 'src', 'samples.ts'),
  `// generated by scripts/embed-samples.ts - do not edit\nexport const SAMPLES: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`embedded ${names.length} samples`);
